// The 13 themes, with the same colors as the web version (generated from its style.css).
use eframe::egui::Color32;

const fn rgba(r: u8, g: u8, b: u8, a: u8) -> Color32 {
    Color32::from_rgba_premultiplied(
        (r as u16 * a as u16 / 255) as u8,
        (g as u16 * a as u16 / 255) as u8,
        (b as u16 * a as u16 / 255) as u8,
        a,
    )
}

#[derive(Clone, Copy)]
pub struct Theme {
    pub id: &'static str,
    pub name: &'static str,
    pub dark: bool,
    pub bg: Color32,
    pub surface: Color32,        // the panels (see-through over the background)
    pub surface_strong: Color32, // the player bar and popups
    pub menu: Color32,
    pub text: Color32,
    pub muted: Color32,
    pub border: Color32,
    pub hover: Color32,
    pub track: Color32,          // empty part of sliders and bars
    pub accent: Color32,
    pub accent2: Color32,
    pub accent_soft: Color32,
    pub on_accent: Color32,      // text and icons on the accent color
    pub danger: Color32,
    pub warning: Color32,
    pub glow: f32,               // how strong the colored glow in the background is
}

